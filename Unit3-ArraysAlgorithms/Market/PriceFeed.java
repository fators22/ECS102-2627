import java.net.HttpURLConnection;
import java.net.URI;
import java.net.URL;
import java.util.Locale;
import java.util.Scanner;

/**
 * PriceFeed - live stock prices from Finnhub (finnhub.io) for the Financial Monitor lab.
 * readLine() returns "PRICE TICK_CHANGE" (e.g. "189.84 +0.12").
 *
 *   new PriceFeed("AAPL")   Live stock price. Never ends. Stop it with Ctrl+C or the stop button.
 *
 * Setup: get a free API key at finnhub.io and paste it into API_KEY below.
 * Prices only change while the market is open (9:30 AM - 4:00 PM ET, Mon-Fri).
 * readLine() throws Exception, so main in MonitorRunner must say: throws Exception
 * Students do not edit this file (except API_KEY).
 */
public class PriceFeed
{
    private static final String API_KEY = "PASTE_YOUR_KEY_HERE";
    private static final int POLL_MS = 2000;   // one request every 2 seconds (free limit: 60 per minute per key)

    private String symbol;
    private double lastPrice;
    private boolean first;

    public PriceFeed(String symbol)
    {
        this.symbol = symbol.toUpperCase();
        first = true;
    }

  

    // Finnhub response: {"c":189.84,"d":1.2,"dp":0.63,...}
    // c (current price) is always the first value, so read only up to the first comma
    public double fetchPrice() throws Exception
    {
        String url = "https://finnhub.io/api/v1/quote?symbol=" + symbol + "&token=" + API_KEY;
        String data = readUrl(url);

        int start = data.indexOf(":") + 1;    // first colon, right after "c"
        int end = data.indexOf(",");          // first comma, end of the price
        double price = Double.parseDouble(data.substring(start, end));

        if (price == 0)
        {
            throw new Exception("No price for \"" + symbol + "\". Check the symbol.");
        }
        return price;
    }

    private String readUrl(String address) throws Exception
    {
        URL url = URI.create(address).toURL();
        HttpURLConnection conn = (HttpURLConnection) url.openConnection();

        int code = conn.getResponseCode();
        if (code != 200)
        {
            throw new Exception("HTTP " + code);
        }

        Scanner in = new Scanner(conn.getInputStream());
        String data = in.nextLine();   // the whole response is one line
        in.close();
        return data;
    }
}
